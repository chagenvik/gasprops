@pytest.mark.parametrize("case", _REFERENCE_CASES, ids=[c["name"] for c in _REFERENCE_CASES])
def test_aga8_pt_reference_vectors(case: dict) -> None:
    adapter = pvtlib.AGA8(case["equation"])
    result = adapter.calculate_from_PT(
        composition=case["composition"],
        pressure=case["pressure_kPa"],
        temperature=case["temperature_K"],
        pressure_unit="kPa",
        temperature_unit="K",
    )

    for prop, expected in case["expected"].items():
        assert result[prop] == pytest.approx(expected, rel=1e-10, abs=1e-10)


@pytest.mark.parametrize(
    "pressure,temperature,pressure_unit,temperature_unit",
    [
        (4_000_000.0, 293.15, "Pa", "K"),
        (580.1509509, 68.0, "psi", "F"),
        (38.98675, 20.0, "barg", "C"),
        (40.0, 68.0, "bara", "F"),
        (565.4550021, 68.0, "psig", "F"),
        (4.0, 20.0, "MPa", "C"),
    ],
)
def test_aga8_gerg_n2_unit_conversion_density(
    pressure: float,
    temperature: float,
    pressure_unit: str,
    temperature_unit: str,
) -> None:
    gerg = pvtlib.AGA8("GERG-2008")
    result = gerg.calculate_from_PT(
        composition={"N2": 100.0},
        pressure=pressure,
        temperature=temperature,
        pressure_unit=pressure_unit,
        temperature_unit=temperature_unit,
    )
    assert result["rho"] == pytest.approx(46.242, abs=1e-3)


def test_comparison_grid_uses_gerg_and_detail_pathways() -> None:
    case = _REFERENCE_CASES[0]
    values = _run_grid(
        composition=case["composition"],
        pressures=[case["pressure_kPa"]],
        temperature=case["temperature_K"],
        p_unit="kPa",
        t_unit="K",
    )

    assert values["rho_gerg"][0] == pytest.approx(_REFERENCE_CASES[0]["expected"]["rho"], rel=1e-10, abs=1e-10)
    assert values["rho_detail"][0] == pytest.approx(_REFERENCE_CASES[1]["expected"]["rho"], rel=1e-10, abs=1e-10)
    assert values["z_gerg"][0] == pytest.approx(_REFERENCE_CASES[0]["expected"]["z"], rel=1e-10, abs=1e-10)
    assert values["z_detail"][0] == pytest.approx(_REFERENCE_CASES[1]["expected"]["z"], rel=1e-10, abs=1e-10)
